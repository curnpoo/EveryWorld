//! Dataset registry (`data/registry/*.toml`), the licence gate and the credits generator.
//! Schema and rules: `docs/data/README.md` section 5.

use anyhow::{Context, Result, bail};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::path::Path;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
#[allow(dead_code)] // every schema field is validated on load, not all are read
pub struct Dataset {
    pub id: String,
    pub name: String,
    pub organisation: String,
    /// `data`, `code` or `asset`.
    pub kind: String,
    pub urls: Vec<String>,
    #[serde(default)]
    pub coverage: String,
    #[serde(default)]
    pub resolution: String,
    #[serde(default)]
    pub format: String,
    pub licence: String,
    pub licence_url: String,
    /// `yes`, `no` or `conditions`.
    pub commercial: String,
    pub modification: String,
    pub redistribution: String,
    #[serde(default)]
    pub attribution: String,
    /// `GREEN`, `YELLOW`, `RED`, or `DEV` (development only, never packaged).
    pub screening: String,
    #[serde(default)]
    pub review_notes: String,
    /// Date (YYYY-MM-DD) a person read the licence at `licence_url`; empty = not yet checked.
    #[serde(default)]
    pub licence_checked: String,
    #[serde(default)]
    pub consumers: Vec<String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct DataVersion {
    version: u32,
    #[allow(dead_code)]
    description: String,
    /// Dataset id -> pinned release, or "unpinned" for datasets not yet acquired.
    datasets: BTreeMap<String, String>,
}

fn read_dir(dir: &Path) -> Result<Vec<std::path::PathBuf>> {
    let mut v: Vec<_> = std::fs::read_dir(dir)
        .with_context(|| dir.display().to_string())?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e == "toml"))
        .collect();
    v.sort();
    Ok(v)
}

pub fn load(root: &Path) -> Result<BTreeMap<String, Dataset>> {
    let mut out = BTreeMap::new();
    for p in read_dir(&root.join("data/registry"))? {
        let d: Dataset = toml::from_str(&std::fs::read_to_string(&p)?)
            .with_context(|| p.display().to_string())?;
        if p.file_stem().and_then(|s| s.to_str()) != Some(d.id.as_str()) {
            bail!("{}: file name must equal id `{}`", p.display(), d.id);
        }
        if !["GREEN", "YELLOW", "RED", "DEV"].contains(&d.screening.as_str()) {
            bail!("{}: unknown screening `{}`", p.display(), d.screening);
        }
        if d.licence_url.is_empty() {
            bail!("{}: licence_url is required", p.display());
        }
        out.insert(d.id.clone(), d);
    }
    Ok(out)
}

/// Fails if any data version (the list of datasets a pack may be built from) names an unknown,
/// RED or DEV dataset, or a YELLOW one without review notes. With `EW_GATE_SHIP=1` it also
/// fails on any dataset whose licence has not been checked against its source, and on "unpinned".
pub fn gate(root: &Path) -> Result<()> {
    let reg = load(root)?;
    let ship = std::env::var("EW_GATE_SHIP").is_ok();
    let (mut errors, mut warnings) = (Vec::new(), Vec::new());
    for p in read_dir(&root.join("data/versions"))? {
        let v: DataVersion = toml::from_str(&std::fs::read_to_string(&p)?)
            .with_context(|| p.display().to_string())?;
        for (id, pin) in &v.datasets {
            let tag = format!("data version {} / {id}", v.version);
            let Some(d) = reg.get(id) else {
                errors.push(format!("{tag}: no registry entry"));
                continue;
            };
            match d.screening.as_str() {
                "RED" => errors.push(format!("{tag}: RED ({})", d.licence)),
                "DEV" => errors.push(format!("{tag}: development-only source")),
                "YELLOW" if d.review_notes.trim().is_empty() => {
                    errors.push(format!("{tag}: YELLOW without review notes"))
                }
                _ => {}
            }
            let soft = if ship { &mut errors } else { &mut warnings };
            if d.licence_checked.is_empty() {
                soft.push(format!("{tag}: licence not yet checked against its source"));
            }
            if pin == "unpinned" {
                soft.push(format!("{tag}: release not pinned"));
            }
        }
    }
    for w in &warnings {
        eprintln!("licence-gate: warning: {w}");
    }
    for e in &errors {
        eprintln!("licence-gate: ERROR: {e}");
    }
    if !errors.is_empty() {
        bail!("{} licence gate failure(s)", errors.len());
    }
    println!("licence-gate: pass ({} registry entries, {} warning(s))", reg.len(), warnings.len());
    Ok(())
}

pub fn credits(root: &Path, check: bool) -> Result<()> {
    let reg = load(root)?;
    let mut s = String::from(
        "# Credits\n\nGenerated by `cargo xtask credits` from `data/registry/`. Do not edit by hand.\n",
    );
    for (kind, title) in [("data", "Data"), ("code", "Code"), ("asset", "Assets")] {
        s += &format!("\n## {title}\n\n");
        for d in reg.values().filter(|d| d.kind == kind && matches!(d.screening.as_str(), "GREEN" | "YELLOW")) {
            let attr = if d.attribution.is_empty() { String::new() } else { format!(" {}", d.attribution) };
            s += &format!("- **{}** — {}. Licence: [{}]({}).{}\n", d.name, d.organisation, d.licence, d.licence_url, attr);
        }
    }
    let path = root.join("CREDITS.md");
    if check {
        if std::fs::read_to_string(&path).unwrap_or_default() != s {
            bail!("CREDITS.md is out of date; run `cargo xtask credits`");
        }
        println!("credits: up to date");
    } else {
        std::fs::write(&path, s)?;
        println!("credits: wrote CREDITS.md");
    }
    Ok(())
}
