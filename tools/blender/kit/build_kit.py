"""Build the BIO_FOR building kit.

  Blender --background --factory-startup --python tools/blender/kit/build_kit.py -- \
      --out target/kit [--only NAME ...] [--previews]

Writes <out>/glb/<NAME>.glb, <out>/previews/<NAME>.png (with --previews) and
<out>/kit.toml (full builds only). Exits non-zero if any part fails validation.
"""

import argparse
import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import kitlib  # noqa: E402
import parts  # noqa: E402


def fresh_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    return bpy.context.scene


def fmt(v):
    return "[" + ", ".join(f"{x:.4f}" for x in v) + "]"


def tstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_toml(path, rows):
    L = ["# Generated by tools/blender/kit/build_kit.py. Do not edit by hand.",
         "# Positions are part-local, metres, Blender axes (Z up; outer face toward -Y).",
         "# In the .glb the same point (x, y, z) is stored as (x, z, -y) (+Y up).",
         "", "[kit]", 'family = "BIO_FOR"', 'units = "m"', "wall_module = [2.0, 0.2, 3.0]",
         "cell = [2.0, 2.0]", "storey_height = 3.0",
         'ground_floor = "foundation top, z=0"',
         'floor_parts = "BIO_FOR_FLOOR_A / BIO_FOR_FLOOR_CORNER_A are for upper storeys only"',
         'x_limit_exception = "BIO_FOR_VERGE_A projects 0.15 m outside the gable plane (x = +-1 of its roof cell)"',
         f"roof_pitch_deg = {parts.PITCH_DEG}", f"roof_rise_per_cell = {parts.RISE:.5f}",
         f"blender = {tstr(bpy.app.version_string)}",
         'socket_orientation = "local +Z of the socket node points along `normal` (out of the surface)"',
         "", "[materials]"]
    for name, d in kitlib.MATERIALS.items():
        extra = "".join(f", {k} = {d[k]}" for k in ("transmission", "ior") if k in d)
        L.append(f"{name} = {{ color = {fmt(d['color'])}, metallic = {d['metallic']}, "
                 f"roughness = {d['roughness']}{extra} }}")
    for r in rows:
        L += ["", "[[part]]", f"name = {tstr(r['name'])}", f"file = {tstr(r['file'])}",
              f"sha256 = {tstr(r['sha256'])}", f"category = {tstr(r['category'])}",
              f"size = {fmt(r['size'])}", f"bbox_min = {fmt(r['bbox_min'])}",
              f"bbox_max = {fmt(r['bbox_max'])}", f"origin = {tstr(r['origin'])}"]
        if r["notes"]:
            L.append(f"notes = {tstr(r['notes'])}")
        L += [f"tris = {r['tris']}", f"tri_budget = {r['budget']}",
              "materials = [" + ", ".join(tstr(m) for m in r["materials"]) + "]"]
        if r["sockets"]:
            L.append("sockets = [")
            for s in r["sockets"]:
                L.append(f"  {{ name = {tstr(s['name'])}, kind = {tstr(s['kind'])}, "
                         f"position = {fmt(s['position'])}, normal = {fmt(s['normal'])} }},")
            L.append("]")
        else:
            L.append("sockets = []")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="target/kit")
    ap.add_argument("--only", action="append", default=[])
    ap.add_argument("--previews", action="store_true")
    a = ap.parse_args(argv)
    out = os.path.abspath(a.out)
    names = a.only or list(parts.PARTS)
    for n in names:
        if n not in parts.PARTS:
            sys.exit(f"unknown part {n}; known: {', '.join(parts.PARTS)}")

    rows, failed = [], []
    for name in names:
        scene = fresh_scene()
        part = parts.PARTS[name]()
        assert part.name == name, (part.name, name)
        obj, rep = part.finalize(scene)
        err, warn = kitlib.validate(part, rep)
        glb = os.path.join(out, "glb", name + ".glb")
        sha = kitlib.export_glb(glb)
        again = os.path.join(out, "glb", name + ".again.glb")
        sha2 = kitlib.export_glb(again)
        os.remove(again)
        if sha != sha2:
            err.append("two exports in one session differ (non-deterministic export)")
        roots = [o.name for o in scene.objects if o.parent is None]
        if roots != [name]:
            err.append(f"scene roots are {roots}, expected only [{name}]")
        status = "FAIL" if err else "ok"
        print(f"KIT {status:4} {name}: tris {rep['tris']}/{kitlib.TRI_BUDGET[part.category]} "
              f"shells {rep['shells']} bbox {fmt(rep['bbox_min'])}..{fmt(rep['bbox_max'])} "
              f"sockets {len(rep['sockets'])} sha {sha[:12]}")
        for m in err:
            print(f"KIT   ERROR {name}: {m}")
        for m in warn:
            print(f"KIT   warn  {name}: {m}")
        if err:
            failed.append(name)
        rows.append(dict(name=name, file=f"glb/{name}.glb", sha256=sha, category=part.category,
                         size=part.size, origin=part.origin, notes=part.notes,
                         budget=kitlib.TRI_BUDGET[part.category], **rep))
        if a.previews:
            lo, hi = rep["bbox_min"], rep["bbox_max"]
            hz = -0.6 if ("FOUNDATION" in name or "ENTRY_STEP" in name) else 0.0
            eng = kitlib.render_preview(scene, os.path.join(out, "previews", name + ".png"),
                                        lo, hi, human_at=(lo[0] - 0.55, min(lo[1], 0.0) - 0.1, hz))
            print(f"KIT   preview {name} ({eng})")

    if a.only:
        print("KIT kit.toml not rewritten (--only build)")
    else:
        write_toml(os.path.join(out, "kit.toml"), rows)
        print(f"KIT wrote {os.path.join(out, 'kit.toml')}")
    if failed:
        print(f"KIT FAILED: {', '.join(failed)}")
        sys.exit(1)
    print(f"KIT all {len(names)} parts ok")


if __name__ == "__main__":
    main()
