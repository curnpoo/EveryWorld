//! Architecture kits: how buildings are actually built in each region.
//!
//! A `Region` (from `style.rs`) has several `Variant`s: distinct local
//! building types (Andalusian white village vs. Provencal vs. Italian
//! palazzo). A variant is picked per *neighborhood* (a ~250 m cell), so a
//! village is coherent, with per-building variation inside it.
//!
//! Everything here is data: palettes, materials, roof forms, window and door
//! design, floor heights, balconies, cornices and prop odds. The generator in
//! `buildings.rs` turns it into geometry.

use crate::meshkit::Arch;
use crate::style::Region;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum WallMat {
    Plaster,
    Brick,
    Stone,
    Siding,
    Concrete,
    Timber,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum RoofMat {
    ClayTile,
    Slate,
    Zinc,
    Shingle,
    Metal,
    Gravel,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RoofForm {
    /// Flat with a parapet.
    Flat,
    Gable,
    Hip,
    /// Shallow hip (Mediterranean, tropical).
    LowHip,
    /// Paris: steep lower slope with dormers, shallow top.
    Mansard,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lintel {
    None,
    /// Plain projecting lintel block.
    Flat,
    /// Lintel with a keystone (European classical).
    Keystone,
    /// Projecting hood mould / pediment.
    Hood,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GroundFloor {
    /// Front door only.
    Door,
    /// Shopfronts on street-facing bays.
    Shops,
    /// Raised stoop with railings (brownstones).
    Stoop,
    /// Arcade / five-foot way (Southeast Asian shophouses).
    Arcade,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Balcony {
    None,
    /// Wrought-iron railing on a thin slab (Paris, Spain).
    Iron,
    /// Solid concrete balcony (modern blocks).
    Concrete,
    /// Timber balcony with flower boxes (Alpine).
    Timber,
    /// Railing flush with the window, no slab.
    Juliet,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Cornice {
    None,
    Simple,
    Classical,
    /// Deep bracketed cornice (NYC tenements, Italianate).
    Bracketed,
}

#[derive(Debug, Clone, Copy)]
pub struct WindowDesign {
    pub w: f32,
    pub h: f32,
    pub sill_h: f32,
    pub arch: Arch,
    /// Mullion columns and rows (1,1 = single pane).
    pub cols: u8,
    pub rows: u8,
    pub frame: u32,
    pub lintel: Lintel,
    /// Stone surround (architrave) around the opening.
    pub surround: bool,
    /// Iron grille over the glass.
    pub grille: bool,
    /// Probability a window has shutters.
    pub shutters: f32,
    pub shutter_colors: &'static [u32],
    pub recess: f32,
}

#[derive(Debug, Clone, Copy)]
pub struct PropOdds {
    pub ac_unit: f32,
    pub fire_escape: f32,
    pub satellite: f32,
    pub water_tank: f32,
    pub rooftop_garden: f32,
    pub solar: f32,
    pub chimney: f32,
    pub flower_box: f32,
    pub awning: f32,
}

pub const NO_PROPS: PropOdds = PropOdds {
    ac_unit: 0.0,
    fire_escape: 0.0,
    satellite: 0.0,
    water_tank: 0.0,
    rooftop_garden: 0.0,
    solar: 0.0,
    chimney: 0.0,
    flower_box: 0.0,
    awning: 0.0,
};

#[derive(Debug, Clone, Copy)]
pub struct Variant {
    pub name: &'static str,
    pub weight: f32,
    pub walls: &'static [u32],
    pub wall_mat: WallMat,
    /// Optional contrasting ground floor (stone base, whitewashed plinth).
    pub base: Option<(u32, WallMat)>,
    pub trim: &'static [u32],
    pub doors: &'static [u32],
    pub roof_forms: &'static [RoofForm],
    pub roof_mat: RoofMat,
    pub roofs: &'static [u32],
    /// Roof rise per meter of half-span.
    pub pitch: f32,
    pub overhang: f32,
    pub floor_h: f32,
    pub ground_h: f32,
    pub floors: (u8, u8),
    pub bay_w: f32,
    pub window: WindowDesign,
    pub ground: GroundFloor,
    pub balcony: Balcony,
    /// Floor indices (ground = 0) that get balconies; `&[0]` means every
    /// upper floor.
    pub balcony_floors: &'static [u8],
    pub balcony_odds: f32,
    pub cornice: Cornice,
    pub string_courses: bool,
    pub plinth: bool,
    pub props: PropOdds,
    /// Detached house extras: garage, porch, driveway, mailbox, fence.
    pub house: bool,
}

const WHITE_FRAME: u32 = 0xf4f2ec;
const DARK_FRAME: u32 = 0x3a3d42;
const WOOD_FRAME: u32 = 0x6b4a2f;

pub fn variants(r: Region) -> &'static [Variant] {
    match r {
        Region::NorthAmericaCity => NA_CITY,
        Region::NorthAmericaSuburb => NA_SUBURB,
        Region::LatinAmerica => LATAM,
        Region::Mediterranean => MEDITERRANEAN,
        Region::Paris => PARIS,
        Region::WesternEurope => WESTERN_EU,
        Region::Alpine => ALPINE,
        Region::British => BRITISH,
        Region::Nordic => NORDIC,
        Region::EasternEurope => EASTERN_EU,
        Region::NorthAfricaMiddleEast => MENA,
        Region::SubSaharan => SUBSAHARAN,
        Region::SouthAsia => SOUTH_ASIA,
        Region::EastAsia => EAST_ASIA,
        Region::Japan => JAPAN,
        Region::SoutheastAsia => SE_ASIA,
        Region::Oceania => OCEANIA,
    }
}

/// Pick a variant for a building: coherent per neighborhood cell, weighted.
pub fn pick(r: Region, neighborhood: u64, seed: u64) -> &'static Variant {
    let vs = variants(r);
    // 80% of buildings follow the neighborhood's variant, 20% mix in others.
    let roll = if crate::hash01(seed, 77) < 0.8 { crate::hash01(neighborhood, 5) } else { crate::hash01(seed, 6) };
    let total: f32 = vs.iter().map(|v| v.weight).sum();
    let mut acc = 0.0;
    for v in vs {
        acc += v.weight / total;
        if roll <= acc {
            return v;
        }
    }
    &vs[vs.len() - 1]
}

const fn win(w: f32, h: f32, sill_h: f32, arch: Arch, cols: u8, rows: u8, frame: u32, lintel: Lintel) -> WindowDesign {
    WindowDesign { w, h, sill_h, arch, cols, rows, frame, lintel, surround: false, grille: false, shutters: 0.0, shutter_colors: &[], recess: 0.16 }
}

