#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_region_has_variants_and_picks_deterministically() {
        for r in Region::ALL {
            assert!(!variants(r).is_empty(), "{r:?}");
            let a = pick(r, 42, 7).name;
            let b = pick(r, 42, 7).name;
            assert_eq!(a, b);
        }
    }

    #[test]
    fn neighborhoods_are_coherent() {
        // Most buildings in one neighborhood share its variant.
        let r = Region::Mediterranean;
        let main = pick(r, 1234, u64::MAX).name; // seed chosen so 80% branch decides
        let same = (0..200u64).filter(|s| pick(r, 1234, *s).name == main).count();
        assert!(same > 120, "{same}/200 share the neighborhood variant");
    }
}
