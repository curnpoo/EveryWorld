// Generates data/cars.json from the engine sound kit's cars.js, so the Rust
// port never hand-retypes car data. Run from the repo root after updating
// vendor/engine-sound-kit:
//
//   node crates/ed_engine_audio/tools/gen_cars.mjs
//
// Every car is written resolved (resolveCar: its sound merged over
// DEFAULT_SOUND, engine.cyl filled in), which is what the voice consumes.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CARS, DEFAULT_SOUND, GEARBOX, resolveCar } from '../../../vendor/engine-sound-kit/cars.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = {
  note: 'GENERATED by tools/gen_cars.mjs from vendor/engine-sound-kit/cars.js. Do not edit by hand.',
  defaultSound: DEFAULT_SOUND,
  gearbox: GEARBOX,
  cars: CARS.map(c => ({ group: c.group, tagline: c.tagline, ...resolveCar(c) })),
};
const path = join(here, '..', 'data', 'cars.json');
writeFileSync(path, JSON.stringify(out, null, 1) + '\n');
console.log(`wrote ${out.cars.length} cars to ${path}`);
